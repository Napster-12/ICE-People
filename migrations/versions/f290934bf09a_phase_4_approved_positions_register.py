OPEN_REQUISITION = ("Draft", "Submitted", "In Approval", "Returned", "Approved", "Advertised", "Interviewing", "Offer")


def split_positions():
    """Each old row held `headcount` seats: keep it as the first seat and add copies for the rest. Every seat
    gets a POS number; current holders and open requisitions are spread over the seats; each financial year
    that had positions gets an approved register."""
    conn = op.get_bind()
    stamp, today = datetime.now(), date.today()
    year = today.year
    seq = conn.execute(sa.text("SELECT last FROM ref_sequences WHERE prefix = 'POS' AND year = :y"), {"y": year}).scalar()
    counter = [seq or 0]

    def number():
        counter[0] += 1
        return f"POS-{year}-{counter[0]:05d}"

    rows = conn.execute(sa.text("SELECT id, department_id, cost_centre_id, job_grade_id, title, headcount, "
                                "financial_year, critical FROM approved_positions ORDER BY id")).mappings().all()
    for row in rows:
        seats = [row["id"]]
        conn.execute(sa.text("UPDATE approved_positions SET position_number = :n, created_at = :s, updated_at = :s "
                             "WHERE id = :id"), {"n": number(), "s": stamp, "id": row["id"]})
        for _ in range(max(1, row["headcount"] or 1) - 1):
            result = conn.execute(sa.text(
                "INSERT INTO approved_positions (department_id, cost_centre_id, job_grade_id, title, headcount, "
                "financial_year, critical, status, is_ad_hoc, position_number, created_at, updated_at) "
                "VALUES (:d, :cc, :g, :t, 1, :fy, :c, 'Vacant', 0, :n, :s, :s)"),
                {"d": row["department_id"], "cc": row["cost_centre_id"], "g": row["job_grade_id"], "t": row["title"],
                 "fy": row["financial_year"], "c": row["critical"], "n": number(), "s": stamp})
            seats.append(result.lastrowid)
        conn.execute(sa.text("UPDATE approved_positions SET status = 'Vacant', vacant_since = :d WHERE id IN (%s)"
                             % ",".join(str(i) for i in seats)), {"d": today})
        free = list(seats)
        holders = conn.execute(sa.text("SELECT id FROM employees WHERE approved_position_id = :p AND status NOT IN "
                                       "('Exited', 'Archived') ORDER BY id"), {"p": row["id"]}).scalars().all()
        for emp_id in holders:
            if not free:
                break
            seat = free.pop(0)
            conn.execute(sa.text("UPDATE employees SET approved_position_id = :s WHERE id = :e"), {"s": seat, "e": emp_id})
            conn.execute(sa.text("UPDATE approved_positions SET status = 'Filled', vacant_since = NULL WHERE id = :s"),
                         {"s": seat})
        reqs = conn.execute(sa.text("SELECT id, status FROM requisitions WHERE approved_position_id = :p AND status IN "
                                    "(%s) ORDER BY id" % ",".join(f"'{s}'" for s in OPEN_REQUISITION)),
                            {"p": row["id"]}).mappings().all()
        for req in reqs:
            if not free:
                break
            seat = free.pop(0)
            conn.execute(sa.text("UPDATE requisitions SET approved_position_id = :s WHERE id = :r"),
                         {"s": seat, "r": req["id"]})
            if req["status"] not in ("Draft", "Submitted", "In Approval", "Returned"):
                conn.execute(sa.text("UPDATE approved_positions SET status = 'In recruitment' WHERE id = :s"), {"s": seat})
    if rows:
        if seq is None:
            conn.execute(sa.text("INSERT INTO ref_sequences (prefix, year, last) VALUES ('POS', :y, :l)"),
                         {"y": year, "l": counter[0]})
        else:
            conn.execute(sa.text("UPDATE ref_sequences SET last = :l WHERE prefix = 'POS' AND year = :y"),
                         {"y": year, "l": counter[0]})
    for fy in conn.execute(sa.text("SELECT DISTINCT financial_year FROM approved_positions")).scalars().all():
        conn.execute(sa.text("INSERT INTO position_registers (financial_year, status, approved_at) "
                             "VALUES (:fy, 'Approved', :s)"), {"fy": fy, "s": stamp})


