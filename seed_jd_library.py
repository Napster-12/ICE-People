# ATS weights for hands-on roles where experience and skills matter more than qualifications.
HANDS_ON = {"required": 50, "preferred": 10, "experience": 30, "education": 0, "keywords": 10}


def jd(title, family, education, years, about, duties, qualifications, competencies, conditions, required, preferred,
       criteria, scale, ats_weights=None):
    """One JD. duties: [(sub-heading, [bullets])]; criteria: [(name, weight)], weights total 100."""
    return {"title": title, "family": family, "education": education, "years": years, "about": about,
            "duties": duties, "qualifications": qualifications, "competencies": competencies,
            "conditions": conditions, "required": required, "preferred": preferred, "criteria": criteria,
            "scale": scale, "ats_weights": ats_weights}


def description(role):
    parts = ["ABOUT THE ROLE", *role["about"], "", "KEY RESPONSIBILITIES"]
    for heading, bullets in role["duties"]:
        parts += [heading, *(f"- {b}" for b in bullets)]
    parts += ["", "QUALIFICATIONS AND EXPERIENCE", *(f"- {q}" for q in role["qualifications"]),
              "", "SKILLS AND COMPETENCIES", *(f"- {c}" for c in role["competencies"]),
              "", "WORKING CONDITIONS", *(f"- {c}" for c in role["conditions"])]
    return "\n".join(parts)


