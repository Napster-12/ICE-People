def add():
    from app.models import JobDescriptionTemplate, JobFamily
    from app.services import ats, audit
    from app.services.dates import today

    existing = {t.title.lower() for t in JobDescriptionTemplate.query.all()}
    families = {f.code: f for f in JobFamily.query.all()}
    added = 0
    for i, role in enumerate(ROLES):
        if role["title"].lower() in existing:
            continue
        weights, weight_errors = (ats.parse_weights(role["ats_weights"]) if role["ats_weights"] else (None, []))
        assert not weight_errors, (role["title"], weight_errors)
        template = JobDescriptionTemplate(
            title=role["title"], job_family_id=families[role["family"]].id, description=description(role),
            required_skills=role["required"], preferred_skills=role["preferred"], min_experience=role["years"],
            min_education=role["education"], ats_weights=weights,
            review_date=today() + timedelta(days=10 + (i * 41) % 365), active=True)
        db.session.add(template)
        db.session.flush()
        audit.record("create", "jd_template", template.id, after={"title": template.title},
                     detail="Dummy JD library (seed_jd_library.py)")
        added += 1
    db.session.commit()
    print(f"Added {added} job descriptions ({len(ROLES) - added} already in the library).")


def remove():
    from app.models import Job, JobDescriptionTemplate

    titles = {r["title"].lower() for r in ROLES}
    used = {j.jd_template_id for j in Job.query.filter(Job.jd_template_id.isnot(None))}
    removed = kept = 0
    for template in JobDescriptionTemplate.query.all():
        if template.title.lower() not in titles:
            continue
        if template.updated_by_id is not None or template.id in used:
            kept += 1                                        # edited by someone, or an advert came from it
            continue
        db.session.delete(template)
        removed += 1
    db.session.commit()
    print(f"Removed {removed} job descriptions; kept {kept} that were edited or used for an advert.")


